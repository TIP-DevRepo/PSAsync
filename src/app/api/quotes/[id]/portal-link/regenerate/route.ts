import { NextRequest, NextResponse } from "next/server"
import { prisma } from "@/lib/prisma"
import { notFound, requireAccess } from "@/lib/api-access"
import { loadViewableQuote, quoteWhere } from "@/lib/scoped-loaders"
import { clientLinkOpens } from "@/lib/portal-access"
import { newAccessToken } from "@/lib/portal-token"
import { actorName, withNote } from "@/lib/quote-sender"

// Replaces the customer link so every link sent before stops working
// immediately. Each version of a quote is its own row with its own client
// token, and a customer may hold a link to any version that was sent (or
// to a draft revision, which opens the last sent version), so every
// version in the family gets a new token. The internal preview token is
// left alone. The change is noted at the top of this version's internal
// notes, the same way a send as is.
export async function POST(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { ctx, response } = await requireAccess({
    permission: "quotes.edit",
    message: "You do not have permission to edit quotes",
  })
  if (response) return response

  const { id } = await params
  const viewable = await loadViewableQuote(ctx, id)
  if (!viewable) return notFound()

  const family = await prisma.quote.findMany({
    where: { companyId: ctx.companyId, quoteNumber: viewable.quoteNumber },
    select: { id: true, internalNotes: true },
  })
  const current = family.find((q) => q.id === viewable.id)
  if (!current) return notFound()

  const note = `[Customer link regenerated by ${await actorName(ctx)}]`
  const updated = await prisma.$transaction(async (tx) => {
    for (const row of family) {
      if (row.id === current.id) continue
      await tx.quote.update({ where: quoteWhere(ctx, row.id), data: { accessToken: newAccessToken() } })
    }
    return tx.quote.update({
      where: quoteWhere(ctx, current.id),
      data: { accessToken: newAccessToken(), internalNotes: withNote(current.internalNotes, note) },
      select: { accessToken: true, status: true, sentAt: true },
    })
  })

  return NextResponse.json({
    url: `${req.nextUrl.origin}/portal/${updated.accessToken}`,
    opens: clientLinkOpens(updated),
  })
}
